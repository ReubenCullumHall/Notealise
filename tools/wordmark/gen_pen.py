# A keyframe per piece is no longer enough: speed now varies WITHIN a stroke, and CSS
# interpolates offset-distance linearly between keyframes, so the dot would cut the
# corner off every speed change and drift off the ink front. Emit one wherever the
# weight steps, plus a floor of KF_PER_STROKE evenly spaced, so the dot and the ink stay
# locked together whatever the routing does.
