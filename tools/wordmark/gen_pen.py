def new_ink(pts, radius):
    """How much NEW ink each sample exposes — measured, by sweeping the reveal disc over
    a grid and counting cells that were not already covered.

    Time is handed out in proportion to this, and that is the whole point: the ink front
    should advance evenly, and under constant pen speed it does not. Two separate things
    break it, and counting pixels catches both without modelling either.

      * The disc's radius follows the letter's local thickness, so it is not constant.
        Where it grows, the front runs out ahead of the pen; where it shrinks, the front
        stops dead while the pen carries on. That is the hitch in `s` about a third of the
        way through, where consecutive segment widths run 401, 401, 362, 268.
      * Where the stroke crosses or doubles back on itself the disc is over ink that is
        already painted and contributes nothing at all. `a` does this deliberately (it
        comes back down its own stem); `s` and `e` each cross once.

    Under constant speed both read the same way to a viewer: the ink stops while the dot
    keeps going. And because the dot is the same colour as the ink it is crossing, that
    looks like the animation hanging rather than like a pen travelling."""
    x0, y0 = pts.min(0) - radius.max() - GRID
    x1, y1 = pts.max(0) + radius.max() + GRID
    W = int((x1 - x0) / GRID) + 2
    H = int((y1 - y0) / GRID) + 2
    gx = x0 + np.arange(W) * GRID
    gy = y0 + np.arange(H) * GRID
    covered = np.zeros((H, W), bool)
    gained = np.zeros(len(pts))
    for i, (p, r) in enumerate(zip(pts, radius)):
        cx0 = max(0, int((p[0] - r - x0) / GRID))
        cx1 = min(W, int((p[0] + r - x0) / GRID) + 2)
        cy0 = max(0, int((p[1] - r - y0) / GRID))
        cy1 = min(H, int((p[1] + r - y0) / GRID) + 2)
        sub = covered[cy0:cy1, cx0:cx1]
        dx = gx[cx0:cx1] - p[0]
        dy = gy[cy0:cy1] - p[1]
        disc = (dx[None, :] ** 2 + dy[:, None] ** 2) <= r * r
        gained[i] = np.count_nonzero(disc & ~sub)
        sub |= disc
    return gained


def weighted_cum(pts, w):
    """Cumulative 'time length' along a stroke, and its total."""
    seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
    wseg = seg * 0.5 * (w[:-1] + w[1:])
    return np.concatenate([[0.0], np.cumsum(wseg)])


def ink_weights(pts, cov):
    """dt/ds, from new ink per unit length: linger where a lot of ink is appearing, hurry
    where little or none is. Normalised to a median of 1 and clamped, so a stretch the pen
    has already painted is crossed briskly rather than teleported over."""
    seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
    seg = np.concatenate([[seg[0]], seg])
    rate = new_ink(pts, cov * MASK_SAFETY) / np.maximum(seg, 1e-9)
    pad = np.pad(rate, SMOOTH_W // 2, mode="edge")
    rate = np.convolve(pad, np.ones(SMOOTH_W) / SMOOTH_W, "valid")[:len(rate)]
    ref = np.median(rate[rate > 0]) if np.any(rate > 0) else 1.0
    return np.clip(rate / max(ref, 1e-9), MIN_SPEED, MAX_SPEED)


