maxw = {i: 0 for i in range(5)}

# ONE width per letter, and that is the whole point of it.
#
# Each segment is a round-capped stroke, so the revealed region is the union of a chain of
# discs. Give each segment its own width — which the coverage figures invite, since the
# requirement varies along a letter — and that chain becomes a lumpy sausage: bulge,
# pinch, bulge. Wherever a segment's disc is narrower than the glyph is thick, the glyph's
# own edge is not reached and a notch shows, which fills in a moment later when a wider
# neighbour arrives. The `s` ran 258-422 across its length and looked like a caterpillar
# rather than a pen — the ink is visible before the stroke that makes it exists, which is
# exactly what it must not do. Reported 2026-08-12.
#
# A single radius per letter has none of that: the front is one clean round pen tip and
# the reveal boundary is the glyph's own edge everywhere behind it. It costs some ink
# appearing marginally further ahead of the dot on the thin parts, which is the trade, and
# the ink-vs-pen check is what says whether that trade has gone too far.
#
# Per LETTER rather than per word: one width for all five would size every letter to the
# fattest part of the fattest one, and that margin is what runs ahead of the pen.
width_by_letter = {}
for gi in range(5):
    idxs = [n for n, (g2, _) in enumerate(all_strokes) if g2 == gi]
    width_by_letter[gi] = max(float(cov_by_stroke[n].max()) for n in idxs) * 2 * MASK_SAFETY

# THE REVEAL: one thin ownership slice per step of the journey, switched on whole as the
# pen reaches it. Nothing is swept and nothing is masked - build_centerlines.py's
# ownership_bands() carries the reasoning for why the swept disc had to go.
#
# A slice's clip is exactly the ink the pen lays during that step, so the boundary between
# two consecutive slices is the cut across the stroke that a pen leaves, and the letter's
# own outline is the only other edge on screen. There is no cap to flatten or round, no
# disc to scallop or cusp, and no blob to dump at a letter's start.
#
# Ink leads the pen by at most one slice: a slice switches on when the pen arrives at its
# START, so its far end is inked while the pen crosses it. At 24 slices that is ~4% of a
# letter - inside the pen dot's own radius - and it is what makes the dot read as laying
# the ink rather than chasing it.
ink_slices, ink_fills, ink_keyframes = [], [], []
slice_n = {}
for pi, (kind, gi, pts, t0, t1, tfrac, w_arr, si) in enumerate(pieces):
    if kind != "ink":
        continue
    maxw[gi] = width_by_letter[gi]
    seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
    afrac = np.concatenate([[0.0], np.cumsum(seg)])
    # A degenerate stroke (every point identical) has total length 0, and numpy
    # divides by it without raising — it warns to stderr and hands back NaN,
    # which then bakes garbage slice-reveal timing into the shipped animation.
    # Refuse it out loud instead.
    total = afrac[-1]
    assert total > 0, (
        f"zero-length stroke in {LETTERS[gi]!r} (piece {pi}) — its centreline points are all "
        "the same; re-run build_centerlines.py"
    )
    afrac /= total
    for band in geom[gi].get("bands") or []:
        # The settle pass is a clip with no stretch of journey behind it - it fires when
        # the letter is finished - so it is kept out of the arithmetic below.
        if band.get("fill"):
            ink_fills.append((gi, band["d"], t1))
            continue
        # When does the pen reach the start of this slice? afrac is distance along the
        # path, tfrac is the pacing curve, and the two are indexed together - so this
        # inherits the pen's own slowing and hurrying rather than assuming constant speed.
        i0 = min(int(np.searchsorted(afrac, band["t0"], "left")), len(pts) - 1)
        at = t0 + tfrac[i0] * (t1 - t0)
        k = slice_n.get(gi, 0)
        slice_n[gi] = k + 1
        ink_slices.append((gi, k, band["d"], at, band["t0"]))

# ---- emit ----------------------------------------------------------------------------
# The glyph is defined ONCE per letter and <use>d by each band, so splitting a letter into
# bands costs a clip path and a mask each, not another copy of the outline.
new_groups = []
for gi in range(5):
    L, defs, uses = LETTERS[gi], [], []
    defs.append(f'<path id="glyph-{L}" d="{letter_paths[gi]}"/>')

    # THE REVEAL IS THE SLICES, GATED ONE AT A TIME - the model Reuben approved, restored
    # (2026-08-13, end of day) after a detour through a swept-mask front that is worth
    # recording so nobody walks it again.
    #
    # The sweep (a stroke grown along the centreline, masking the glyph) was added to make
    # the moving front a smooth cut instead of a rasterised slice boundary. It cannot work
    # alone - barely wider than the letter's stroke it still reaches sideways across gaps,
    # so limbs appear before the pen writes them - and with ownership clips holding it
    # honest, every piece boundary it crossed showed as an axe/bowtie wedge at the letter's
    # head, WORSE than the defect it replaced. Butt caps cut flat wedges at pen-down, round
    # caps reveal a half-disc ahead of the pen, and a run-up bends back through a curved
    # opening and reveals a chunk at t=0. Every variant was screenshotted at 6x and each
    # traded one artefact for a bigger one.
    #
    # What actually fixed the reported defects was never the sweep - it was the GEOMETRY:
    #   - the `a`'s entry flick drawn on the way back up (ROUTE), not first, so no stub
    #     strands at the top; the `s` entered bottom-left (HINTS) so it flows up, over,
    #     and down into the curl; the `i` exited at its dot so the tittle lands last.
    #   - the retrace rule in ownership_bands(), which gives a doubled-back stroke its
    #     full width on the first pass instead of splitting it down the middle (the
    #     half-width notch at the top of the `s` and the `a`'s right side).
    #   - the tittle as ONE atomic band (DABS), so the dot lands whole - a dab, the way a
    #     hand dots an i when signing - not as swept fragments with a bite out of it.
    #   - HEAD_FRAC's finer slices at each pen-down, so a wide start reveals in small
    #     quick steps rather than one blob.
    # With those in the geometry, the plain slice reveal is clean: each slice's boundary
    # is a near-perpendicular cut across the stroke (seventh addendum), and the only edges
    # on screen are the letter's outline and that cut.
    for g2, k, clip_d, at, _t0f in ink_slices:
        if g2 != gi or not clip_d:
            continue
        defs.append(f'<clipPath id="sl-{L}-{k}"><path d="{clip_d}"/></clipPath>')
        uses.append(f'<g clip-path="url(#sl-{L}-{k})">'
                    f'<use href="#glyph-{L}" class="wm-letter wm-slice" '
                    f'style="--sliceAt:{at:.0f}ms"/></g>')
    # Last, so it sits on top: anything the slices did not tile, inked once the letter is
    # written. Normally empty - the slices tile the ownership map - but a hole in a
    # finished letter is the one failure that must not be possible.
    for g2, clip_d, at in ink_fills:
        if g2 != gi or not clip_d:
            continue
        defs.append(f'<clipPath id="settle-{L}"><path d="{clip_d}"/></clipPath>')
        uses.append(f'<g clip-path="url(#settle-{L})">'
                    f'<use href="#glyph-{L}" class="wm-letter wm-settle" '
                    f'style="--settleAt:{at:.0f}ms"/></g>')
    # The glyph and the clip paths MUST sit inside <defs>. A bare <path> that is merely
    # referenced still renders where it stands, and with no class on it that is the
    # glyph's fill with no stroke - 29% of each letter, painted on the page from load.
    body = ("            <defs>\n              " + "\n              ".join(defs)
            + "\n            </defs>\n            " + "\n            ".join(uses))
    new_groups.append(f'        <g>\n{body}\n        </g>')
pen_d = "M" + " L".join(f"{p[0]:.1f} {p[1]:.1f}" for p in pen_pts)
new_groups.append(
    f'        <circle class="wm-pen-dot" r="{DOT_R}" aria-hidden="true"\n'
    f"          style=\"offset-path: path('{pen_d}');--penDelay:{ALISE_START}ms;--penDur:{pen_dur:.0f}ms\"/>")

BEG, END = "<!-- wordmark:begin (generated by tools/wordmark/gen_pen.py) -->", "<!-- wordmark:end -->"
block = BEG + "\n" + "\n".join(new_groups) + "\n        " + END
if BEG in html:
    html = re.sub(re.escape(BEG) + r".*?" + re.escape(END), lambda m: block, html, flags=re.S)
else:
    start = html.index('        <g style="--revealDelay:')
    end = html.rindex("</g>") + len("</g>")
    html = html[:start] + "        " + block + html[end:]

html = re.sub(r"    @keyframes dot-r-\w+ \{.*?\}\n", "", html, flags=re.S)
html = re.sub(r"    @keyframes ink-reveal \{.*?\n    \}\n?", "", html, flags=re.S)

# All the generated keyframes live inside ONE delimited region: the pen's offset-distance
# curve plus a dashoffset curve per letter. It has to be delimited rather than matched
# block-by-block, because the count is no longer fixed - a plain "replace @keyframes
# pen-move" would leave last run's five ink-* blocks behind and they would accumulate.
KBEG = "    /* wordmark-keyframes:begin (generated by tools/wordmark/gen_pen.py) */"
KEND = "    /* wordmark-keyframes:end */"
SETTLE_CSS = (
    "    /* THE REVEAL. Each slice of a letter is a clipped copy of the glyph that is off\n"
    "       until the pen reaches it and on from then on - that switch is the whole\n"
    "       animation. `1ms` rather than `0s` because a zero-duration animation is not\n"
    "       required to fire its fill, and `both` is what holds the 0% state through the\n"
    "       delay so nothing is on the page before its turn.\n"
    "\n"
    "       The hiding MUST sit behind the same html.wm-motion gate as the rest of the reveal\n"
    "       (see the head script, and the .wm-note/.wm-caret/.wm-pen-dot rules above) rather than\n"
    "       a bare @media (prefers-reduced-motion: no-preference). A media query alone races\n"
    "       first paint in real Safari: matching a system accessibility setting isn't guaranteed\n"
    "       resolved by the first style pass, so the base (visible) rule can paint for a frame\n"
    "       before the query's hiding rule lands - a flash of the finished word right before it\n"
    "       blanks and replays. `html.wm-motion` is set by a synchronous head script before any\n"
    "       of this markup is parsed, so there is nothing left to race. Under reduced motion, or\n"
    "       with JS off, the class is never added, so a bare `opacity: 0` here would leave the\n"
    "       wordmark blank instead of showing the finished word - outside the gate they still\n"
    "       default to visible, same as before. */\n"
    "    @keyframes wm-settle { to { opacity: 1; } }\n"
    "    html.wm-motion .wm-slice  { opacity: 0; animation: wm-settle 1ms linear var(--sliceAt) both; }\n"
    "    html.wm-motion .wm-settle { opacity: 0; animation: wm-settle 1ms linear var(--settleAt) both; }")
kblock = "\n".join([KBEG, pen_keyframes] + ink_keyframes + [SETTLE_CSS, KEND])
if KBEG in html:
    html = re.sub(re.escape(KBEG) + r".*?" + re.escape(KEND), lambda m: kblock, html, flags=re.S)
elif "@keyframes pen-move" in html:
    html = re.sub(r"    @keyframes pen-move \{.*?\n    \}", lambda m: kblock, html, flags=re.S)
else:
    # The last of the three recognised shapes. If this one doesn't match either,
    # there is nowhere to put the keyframes and the page would be written with none.
    html = must_replace(
        html,
        "    @keyframes dot-trace {\n"
        "      0%, 0.1% { offset-distance: 0%;   opacity: 0; }\n"
        "      0.2%     { offset-distance: 0%;   opacity: 1; }\n"
        "      99.9%    { offset-distance: 100%; opacity: 1; }\n"
        "      100%     { offset-distance: 100%; opacity: 0; }\n"
        "    }",
        kblock,
        "the keyframes block (no marker, no pen-move, no dot-trace)")
# NOT wrapped in must_change: a no-op here is the normal case on every run after the
# first, since the pre-generation form is only present once. The check that matters
# is that the finished rule is in the file either way, which is asserted below.
html = html.replace(
    '      .wm-pen-dot {\n'
    '        animation: dot-trace var(--revealDur) ease-in-out var(--revealDelay) both,\n'
    '                   var(--dotR) var(--revealDur) linear var(--revealDelay) both;\n      }',
    '      .wm-pen-dot { animation: pen-move var(--penDur) linear var(--penDelay) forwards; }')
if "animation: pen-move" not in html:
    sys.exit("gen_pen: .wm-pen-dot is not wired to pen-move — the page's dot rule is in "
             "neither the pre-generation nor the generated form")
# The nudge is `top`, NOT `vertical-align`. .wordmark is inline-flex, so alise is a flex
# item, and vertical-align does not apply to flex items at all - the value written here
# until 2026-08-12 was inert, which is why alise still sat visibly low after the pass that
# "fixed" it. margin-bottom is no good either: a flex item's baseline is synthesised from
# its border box, so margin does not shift it. Verified all four mechanisms in a real
# browser (DESIGN.md, tenth pass). Rewrites the whole declaration block so it is
# idempotent whichever form is currently in the file.
html = must_sub(
    r"\.wm-alise-svg \{[^}]*\}",
    ".wm-alise-svg { display: inline-block; margin-left: 0.06em; overflow: visible;\n"
    f"      position: relative; top: -{NUDGE:.5f}em; }}",
    html, "the .wm-alise-svg rule", count=1)
html = must_sub(
    r'style="height:[\d.]+em;width:[\d.]+em"',
    f'style="height:{0.6463*ALISE_SCALE:.4f}em;width:{1.9194*ALISE_SCALE:.4f}em"',
    html, "the alise svg's height/width style")

open(HTML, "w", encoding="utf-8").write(html)
print("strokes:", len(all_strokes), " pen ends:", round(PEN_END), "ms  (was 4900)")
print(f"alise: scale {ALISE_SCALE}, raised {NUDGE:.5f}em via `top`")
