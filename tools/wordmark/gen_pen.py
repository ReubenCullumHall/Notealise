"""
Rebuild the alise draw as ONE continuous pen.

  * ONE dot for the whole word instead of five. It never fades in or out - it cuts on
    when the first stroke starts and off when the last one ends - and it travels the
    gaps between strokes rather than teleporting, so alise reads as one hand writing
    one word.
  * Dot radius is CONSTANT at the font's own stroke weight (no longer ballooning to
    match local thickness on the fat parts of a letter).
  * Everything is linear, with all pacing carried by the keyframe positions, so the ink
    front and the dot cannot drift apart.

STROKE ORDER IS NOT DECIDED HERE ANY MORE (2026-08-12). geometry.json's `center_d` is
now the finished pen route for each letter - complete, and already in the order a hand
writes it - emitted by `build_centerlines.py`. So `strokes_for()` is the identity, and
the index-slicing stroke plans that used to live in it are gone. They were only ever
needed because the old centerlines missed whole limbs of some letters and had to be
re-cut by hand; read build_centerlines.py's docstring for what that cost.

Mask widths come from the true coverage requirement (every outline point must be
reachable from its nearest centerline sample). That requirement has not changed - what
changed is that a centerline which actually visits the whole letter satisfies it at
roughly the stroke's own width, instead of at up to 1657 units against a 340-unit pen.
Watch the width printout at the end of a run: values near 340-500 are healthy, and
anything approaching four figures means a letter has a limb the pen never reaches, which
will show up as ink flashing on nowhere near the dot.
"""
