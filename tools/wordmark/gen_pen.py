def parse_subpaths(d):
    subs, cur = [], []
    for c, x, y in re.findall(r"([ML])\s*(-?[\d.]+)\s+(-?[\d.]+)", d):
        if c == "M":
            if len(cur) > 1: subs.append(np.array(cur, float))
            cur = [(float(x), float(y))]
        else:
            cur.append((float(x), float(y)))
    if len(cur) > 1: subs.append(np.array(cur, float))
    return subs


def densify(pts, step=STEP):
    out = []
    for i in range(len(pts) - 1):
        seg = pts[i + 1] - pts[i]
        L = float(np.hypot(*seg))
        n = max(1, int(L / step))
        for k in range(n):
            out.append(pts[i] + seg * (k / n))
    out.append(pts[-1])
    return np.array(out)


def plen(p):
    return float(np.sum(np.linalg.norm(np.diff(p, axis=0), axis=1)))


